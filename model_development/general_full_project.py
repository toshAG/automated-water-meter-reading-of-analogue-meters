# Pipeline function
# ------------------------
def process_image(uploaded_image):
    img_rgb = np.array(uploaded_image)
    img_bgr = cv2.cvtColor(img_rgb, cv2.COLOR_RGB2BGR)
    original_rgb = img_rgb.copy()

    # General YOLO
    results = general_model(img_bgr)[0]
    boxes_all = results.boxes.xyxy.cpu().numpy() if len(results.boxes) > 0 else np.empty((0,4))
    classes_all = results.boxes.cls.cpu().numpy() if len(results.boxes) > 0 else np.empty((0,))
    confs_all = results.boxes.conf.cpu().numpy() if len(results.boxes) > 0 else np.empty((0,))
    annotated_all_rgb = to_rgb(results.plot())

    # Separate crops
    dial_crop = None
    pointer_crops = []
    for box, cls in zip(boxes_all, classes_all):
        x1, y1, x2, y2 = map(int, box)
        crop_bgr = img_bgr[y1:y2, x1:x2].copy()
        if int(cls)==0:
            dial_crop = crop_bgr
        else:
            pointer_crops.append({"class":int(cls),"crop":crop_bgr,"box":(x1,y1,x2,y2)})

    # Dial processing
    annotated_dial_rgb = None
    dial_reading_text = "No dial detected"
    dial_reading = ""
    if dial_crop is not None and dial_crop.size !=0:
        odom_results = odometer_yolo(dial_crop)[0]
        odom_boxes = odom_results.boxes.xyxy.cpu().numpy() if len(odom_results.boxes)>0 else np.empty((0,4))
        odom_boxes = sorted(odom_boxes, key=lambda b: b[0]) if len(odom_boxes)>0 else []
        digit_imgs = []
        digit_boxes = []
        for b in odom_boxes:
            x1,y1,x2,y2 = map(int,b)
            crop = dial_crop[y1:y2, x1:x2]
            if crop.size==0: continue
            digit_imgs.append(prepare_cnn_input(crop))
            digit_boxes.append((x1,y1,x2,y2))
        dial_digits = []
        if digit_imgs:
            preds = digit_cnn.predict(np.array(digit_imgs),verbose=0)
            digits = np.argmax(preds,axis=1)
            dial_digits = digits.tolist()
            dial_reading = ''.join(map(str,dial_digits))
            dial_reading_text = f"Dial reading (integer part): {dial_reading}"
        ann_dial = dial_crop.copy()
        if digit_boxes:
            for (box,pred_digit) in zip(digit_boxes,dial_digits):
                x1,y1,x2,y2=box
                cv2.rectangle(ann_dial,(x1,y1),(x2,y2),(0,255,0),2)
                cv2.putText(ann_dial,str(pred_digit),(x1,max(16,y1-6)),cv2.FONT_HERSHEY_SIMPLEX,0.7,(0,255,0),2)
        annotated_dial_rgb = to_rgb(ann_dial)
    if annotated_dial_rgb is None:
        annotated_dial_rgb = to_rgb(dial_crop) if dial_crop is not None else original_rgb.copy()

    # Pointer processing
    annotated_pointers_rgb = img_rgb.copy()
    pointer_readings_text = "No pointers detected"
    pointer_results_list=[]
    ann_ptr = img_bgr.copy()
    decimal_sum=0
    for p in pointer_crops:
        cls=p["class"]
        crop=p["crop"]
        box=p["box"]
        pred=np.argmax(pointer_cnn.predict(np.expand_dims(prepare_cnn_input(crop),axis=0),verbose=0),axis=1)[0]
        pointer_results_list.append({"class":cls,"value":pred})
        x1,y1,x2,y2=box
        cv2.rectangle(ann_ptr,(x1,y1),(x2,y2),(255,0,0),2)
        cv2.putText(ann_ptr,f"Cl{cls}:{pred}",(x1,max(16,y1-6)),cv2.FONT_HERSHEY_SIMPLEX,0.6,(255,0,0),2)
        decimal_sum += pred*SCALES.get(cls,0)
    annotated_pointers_rgb = to_rgb(ann_ptr)
    if pointer_results_list:
        pointer_lines=[]
        for pr in pointer_results_list:
            cls=pr["class"]; val=pr["value"]
            pointer_lines.append(f"Class {cls} → Pred: {val} → scaled: {val*SCALES.get(cls,0):.4f}")
        pointer_readings_text="\n".join(pointer_lines)

    # Final combine
    dial_int = int(dial_reading) if dial_reading else 0
    final_reading_text = f"Final Meter Reading: {dial_int + decimal_sum:.4f}"

    return (original_rgb,
            annotated_all_rgb,
            annotated_dial_rgb,
            annotated_pointers_rgb,
            dial_reading_text,
            pointer_readings_text,
            final_reading_text)

