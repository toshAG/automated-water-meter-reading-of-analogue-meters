import gradio as gr
from ultralytics import YOLO
import cv2
import numpy as np
import tensorflow as tf

# ------------------------
# MODEL PATHS (edit if needed)
# ------------------------
GENERAL_MODEL_PATH = "/content/drive/MyDrive/project/Genaral best.pt"
ODOMETER_YOLO_PATH = "/content/drive/MyDrive/project/odometer_project/odomeeter yolo results/weights/best.pt"
DIGIT_CNN_PATH      = "/content/drive/MyDrive/project/cnn data/digit_cnn_model.h5"
POINTER_CNN_PATH    = "/content/drive/MyDrive/project/pointer_project/pointer_cnn_model.h5"

# ------------------------
# Load models (global, for speed)
# ------------------------
print("Loading models (this may take a few seconds)...")
general_model = YOLO(GENERAL_MODEL_PATH)
odometer_yolo = YOLO(ODOMETER_YOLO_PATH)
digit_cnn = tf.keras.models.load_model(DIGIT_CNN_PATH)
pointer_cnn = tf.keras.models.load_model(POINTER_CNN_PATH)
print("Models loaded.")

# ------------------------
# Scaling rules for pointers
# ------------------------
SCALES = {2: 0.01, 3: 0.001, 4: 0.0001}  # class->multiplier

# ------------------------
# Helper functions
# ------------------------
def draw_boxes_on_image(img_bgr, boxes, classes, confs=None, class_names=None, color=(0,255,0), thickness=2):
    """Draw boxes (xyxy numpy), classes, and optional confidences on image (BGR). Returns annotated BGR."""
    out = img_bgr.copy()
    for i, b in enumerate(boxes):
        x1, y1, x2, y2 = map(int, b)
        cv2.rectangle(out, (x1, y1), (x2, y2), color, thickness)
        label = str(int(classes[i]))
        if class_names is not None:
            # if class name exists
            name = class_names[int(classes[i])] if int(classes[i]) in class_names else label
            label = f"{name}"
        if confs is not None:
            label = f"{label} {confs[i]:.2f}"
        # put text
        cv2.putText(out, label, (x1, max(20, y1-6)), cv2.FONT_HERSHEY_SIMPLEX, 0.6, color, 2, cv2.LINE_AA)
    return out

def to_rgb(img_bgr):
    return cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)

def prepare_cnn_input(crop_bgr, size=(64,64)):
    img = cv2.resize(crop_bgr, size)
    img = img.astype("float32") / 255.0
    return img

# ------------------------
# Pipeline function
# ------------------------
def process_image(uploaded_image):
    """
    uploaded_image: PIL image (from Gradio)
    returns:
      original_rgb,
      annotated_all_rgb,
      annotated_dial_rgb,
      annotated_pointers_rgb,
      dial_reading_text,
      pointer_readings_text,
      final_reading_text
    """
    # Convert PIL -> OpenCV BGR
    img_rgb = np.array(uploaded_image)
    img_bgr = cv2.cvtColor(img_rgb, cv2.COLOR_RGB2BGR)
    original_rgb = img_rgb.copy()

    # 1) Run general YOLO on full image
    results = general_model(img_bgr)[0]  # ultralytics returns list; take first
    boxes_all = results.boxes.xyxy.cpu().numpy() if len(results.boxes) > 0 else np.empty((0,4))
    classes_all = results.boxes.cls.cpu().numpy() if len(results.boxes) > 0 else np.empty((0,))
    confs_all = results.boxes.conf.cpu().numpy() if len(results.boxes) > 0 else np.empty((0,))
    # Annotated full image with all detections
    annotated_all_bgr = results.plot()  # ultralytics helper draws boxes+labels
    annotated_all_rgb = to_rgb(annotated_all_bgr)

    # 2) Separate dial crop and pointer crops (store coordinates too)
    dial_crop = None
    dial_box = None
    pointer_crops = []  # list of dicts {"class":cls, "crop":crop_bgr, "box":box}
    for box, cls in zip(boxes_all, classes_all):
        x1, y1, x2, y2 = map(int, box)
        crop_bgr = img_bgr[y1:y2, x1:x2].copy()
        if int(cls) == 0:
            dial_crop = crop_bgr
            dial_box = (x1, y1, x2, y2)
        else:
            pointer_crops.append({"class": int(cls), "crop": crop_bgr, "box": (x1,y1,x2,y2)})

    # Prepare outputs placeholders
    annotated_dial_rgb = None
    annotated_pointers_rgb = None
    dial_reading_text = "No dial detected"
    pointer_readings_text = "No pointers detected"
    final_reading_text = "N/A"

    # 3) Odometer / Dial processing (Cell 2 logic)
    if dial_crop is not None and dial_crop.size != 0:
        # detect digits inside dial using odometer_yolo (pass dial_crop directly)
        odom_results = odometer_yolo(dial_crop)[0]
        odom_boxes = odom_results.boxes.xyxy.cpu().numpy() if len(odom_results.boxes) > 0 else np.empty((0,4))
        odom_confs = odom_results.boxes.conf.cpu().numpy() if len(odom_results.boxes) > 0 else np.empty((0,))
        # Sort boxes left-to-right
        if len(odom_boxes) > 0:
            odom_boxes = sorted(odom_boxes, key=lambda b: b[0])
        digit_imgs = []
        digit_boxes = []
        for b in odom_boxes:
            x1, y1, x2, y2 = map(int, b)
            # crop relative to dial_crop
            crop = dial_crop[y1:y2, x1:x2]
            if crop.size == 0:
                continue
            digit_input = prepare_cnn_input(crop, size=(64,64))
            digit_imgs.append(digit_input)
            digit_boxes.append((x1,y1,x2,y2))

        dial_digits = []
        if digit_imgs:
            X = np.array(digit_imgs)
            preds = digit_cnn.predict(X, verbose=0)
            digits = np.argmax(preds, axis=1)
            dial_digits = digits.tolist()
            dial_reading = ''.join(map(str, dial_digits))
            dial_reading_text = f"Dial reading (integer part): {dial_reading}"
        else:
            dial_reading_text = "No digits found on dial"

        # create annotated_dial image (draw odometer boxes and predicted digits)
        ann_dial = dial_crop.copy()
        if digit_boxes:
            for (box, pred_digit, conf) in zip(digit_boxes, dial_digits, odom_confs[:len(digit_boxes)]):
                x1,y1,x2,y2 = box
                cv2.rectangle(ann_dial, (x1,y1), (x2,y2), (0,255,0), 2)
                cv2.putText(ann_dial, str(int(pred_digit)), (x1, max(16, y1-6)), cv2.FONT_HERSHEY_SIMPLEX, 0.7, (0,255,0), 2)
        annotated_dial_rgb = to_rgb(ann_dial)
    else:
        dial_reading_text = "⚠️ Dial not detected"

    # 4) Pointer processing (Cell 3 logic)
    pointer_results_list = []
    ann_pointers = img_bgr.copy()  # we'll draw pointer boxes only
    pointer_display_count = 0
    for p in pointer_crops:
        cls = p["class"]
        crop = p["crop"]
        box = p["box"]
        # Prepare pointer CNN input
        input_img = prepare_cnn_input(crop, size=(64,64))
        pred = pointer_cnn.predict(np.expand_dims(input_img, axis=0), verbose=0)
        label = int(np.argmax(pred, axis=1)[0])  # assumes pointer CNN predicts digit labels 0-9
        # store
        pointer_results_list.append({"class": cls, "value": label, "box": box})
        # annotate pointer-only image (draw box + label)
        x1,y1,x2,y2 = box
        cv2.rectangle(ann_pointers, (x1,y1), (x2,y2), (255,0,0), 2)
        cv2.putText(ann_pointers, f"Cl{cls}: {label}", (x1, max(16, y1-6)), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255,0,0), 2)
        pointer_display_count += 1

    if pointer_results_list:
        annotated_pointers_rgb = to_rgb(ann_pointers)
        # Prepare pointer text summary and compute decimal sum
        pointer_lines = []
        decimal_sum = 0.0
        for pr in pointer_results_list:
            cls = pr["class"]; val = pr["value"]
            multiplier = SCALES.get(cls, 0.0)
            decimal_value = val * multiplier
            pointer_lines.append(f"Class {cls} → Pred: {val} → scaled: {decimal_value:.4f}")
            decimal_sum += decimal_value
        pointer_readings_text = "\n".join(pointer_lines)
    else:
        pointer_readings_text = "No pointer crops detected"
        annotated_pointers_rgb = to_rgb(img_bgr)  # show original if none

    # 5) Final combine
    # get dial integer
    dial_int = 0
    if 'dial_reading' in locals() and dial_reading:
        try:
            dial_int = int(dial_reading)
        except:
            dial_int = 0
    final_value = dial_int + (decimal_sum if 'decimal_sum' in locals() else 0.0)
    final_reading_text = f"Final Meter Reading: {final_value:.4f}"

    # If annotated_dial not created (no digits), show dial crop as-is or blank
    if annotated_dial_rgb is None:
        if dial_crop is not None and dial_crop.size != 0:
            annotated_dial_rgb = to_rgb(dial_crop)
        else:
            annotated_dial_rgb = original_rgb.copy()

    # if annotated_pointers_rgb None set to annotated_all
    if annotated_pointers_rgb is None:
        annotated_pointers_rgb = annotated_all_rgb.copy()

    # Return multiple outputs for the dashboard
    return (original_rgb,
            annotated_all_rgb,
            annotated_dial_rgb,
            annotated_pointers_rgb,
            dial_reading_text,
            pointer_readings_text,
            final_reading_text)

