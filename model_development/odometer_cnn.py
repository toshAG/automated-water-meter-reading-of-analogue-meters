    image = cv2.imread(input_image_path)

    if image is None:
        print(f"❌ Failed to load {input_image_path}")
        continue

    # ----------------------------
    # Run YOLO and filter boxes
    # ----------------------------
    results = yolo_model(input_image_path)
    boxes = results[0].boxes  # Boxes object

    filtered_boxes = []

    for b in boxes:
        x1, y1, x2, y2 = map(int, b.xyxy[0].cpu().numpy())
        conf = float(b.conf.cpu().numpy())
        w, h = x2 - x1, y2 - y1

        # Keep boxes that are big enough and confident enough
        if w > 10 and h > 20 and conf > 0.5:
            filtered_boxes.append([x1, y1, x2, y2])

    # Sort left-to-right
    filtered_boxes = sorted(filtered_boxes, key=lambda b: b[0])

    # Optional: take only first 5 boxes
    filtered_boxes = filtered_boxes[:5]

    # ----------------------------
    # Crop digits and save
    # ----------------------------
    os.makedirs('/content/cropped_digits', exist_ok=True)
    cropped_digit_paths = []

    for idx, box in enumerate(filtered_boxes):
        x1, y1, x2, y2 = box
        cropped = image[y1:y2, x1:x2]
        crop_path = f'/content/cropped_digits/img{img_idx}_digit_{idx}.jpg'
        cv2.imwrite(crop_path, cropped)
        cropped_digit_paths.append(crop_path)

    # ----------------------------
    # Preprocess for CNN and predict
    # ----------------------------
    IMG_HEIGHT, IMG_WIDTH = 64, 64
    digit_images = []

    for path in cropped_digit_paths:
        img = cv2.imread(path)
        img = cv2.resize(img, (IMG_WIDTH, IMG_HEIGHT))
        img = img / 255.0
        digit_images.append(img)

    if len(digit_images) == 0:
        print("❌ No digits detected")
        continue

    digit_images = np.array(digit_images, dtype=np.float32)

    pred_probs = cnn_model.predict(digit_images)
    predicted_digits = np.argmax(pred_probs, axis=1)

    # ----------------------------
    # Build final odometer reading
    # ----------------------------
    odometer_reading = ''.join(str(d) for d in predicted_digits)
    print(f"🔢 Predicted odometer reading: {odometer_reading}")

    # ----------------------------
    # Show image with reading
    # ----------------------------
    image_rgb = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)
    plt.figure(figsize=(12, 8))
    plt.imshow(image_rgb)
    plt.axis('off')
    plt.title(f"Image {img_idx+1} → Odometer reading: {odometer_reading}")
    plt.show()

