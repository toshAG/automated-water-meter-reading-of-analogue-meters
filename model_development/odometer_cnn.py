    img = cv2.imread(img_path)

    if img is None:
        print(f"❌ Cannot read {img_path}")
        continue

    results = model.predict(img, verbose=False)

    for r in results:

        boxes = r.boxes

        if boxes is None:
            continue

        crops = []

        # ==============================
        # STEP 1: Extract crops
        # ==============================
        for box in boxes:

            x1, y1, x2, y2 = map(int, box.xyxy[0])
            cls = int(box.cls[0])  # digit class (0–9)

            crop = img[y1:y2, x1:x2]

            if crop.size == 0:
                continue

            crops.append((x1, crop, cls))

        # ==============================
        # STEP 2: Sort left → right (VERY IMPORTANT)
        # ==============================
        crops = sorted(crops, key=lambda x: x[0])

        # ==============================
        # STEP 3: Save into dataset folders
        # ==============================
        for i, (x, crop, cls) in enumerate(crops):

            # grayscale
            crop = cv2.cvtColor(crop, cv2.COLOR_BGR2GRAY)

            # resize
            crop = cv2.resize(crop, (IMG_SIZE, IMG_SIZE))

            # normalize (optional for saving)
            crop = (crop / 255.0 * 255).astype(np.uint8)

            save_folder = os.path.join(output_dataset, str(cls))

            filename = os.path.basename(img_path).split('.')[0]
            save_path = os.path.join(save_folder, f"{filename}_{i}.jpg")

