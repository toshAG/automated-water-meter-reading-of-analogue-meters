def augment_image(img):

    h, w = img.shape[:2]

    # ------------------------------------------------
    # Brightness + Contrast
    # ------------------------------------------------

    alpha = random.uniform(0.85, 1.15)

    beta = random.randint(
        -15,
        15
    )

    img = cv2.convertScaleAbs(
        img,
        alpha=alpha,
        beta=beta
    )

    # ------------------------------------------------
    # Small Rotation
    # ------------------------------------------------

    angle = random.uniform(
        -8,
        8
    )

    M = cv2.getRotationMatrix2D(
        (w / 2, h / 2),
        angle,
        1
    )

    img = cv2.warpAffine(
        img,
        M,
        (w, h),
        borderMode=cv2.BORDER_REPLICATE
    )

    # ------------------------------------------------
    # Small Translation
    # ------------------------------------------------

    tx = random.randint(
        -2,
        2
    )

    ty = random.randint(
        -2,
        2
    )

    M = np.float32(
        [
            [1, 0, tx],
            [0, 1, ty]
        ]
    )

    img = cv2.warpAffine(
        img,
        M,
        (w, h),
        borderMode=cv2.BORDER_REPLICATE
    )

    # ------------------------------------------------
    # Occasional Blur
    # ------------------------------------------------

    if random.random() < 0.2:

        img = cv2.GaussianBlur(
            img,
            (3, 3),
            0
        )

    return img


