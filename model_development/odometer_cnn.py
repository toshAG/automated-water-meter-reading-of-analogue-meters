def save_checkpoint(completed_digits):

    checkpoint = {
        "completed_digits": completed_digits
    }

    with open(checkpoint_file, "w") as f:
        json.dump(checkpoint, f, indent=4)

    print(f"💾 Checkpoint saved: {completed_digits}")


