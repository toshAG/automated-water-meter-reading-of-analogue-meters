def load_checkpoint():

    if os.path.exists(checkpoint_file):

        try:
            with open(checkpoint_file, "r") as f:
                checkpoint = json.load(f)

            print("\n📂 Existing checkpoint found.")
            print("Completed digits:", checkpoint.get("completed_digits", []))

            return checkpoint

        except Exception as e:

            print("⚠️ Could not read checkpoint.")
            print(e)

    return {
        "completed_digits": []
    }


# ================================================================
