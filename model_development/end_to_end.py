# =========================
# HELPER FUNCTION
# =========================
def process_image(img_path):

    img = cv2.imread(img_path)

    # -------------------------
    # STEP 1: GENERAL DETECTION
    # -------------------------
    results = general_model(img_path)

    dial_crop = None
    pointer_crops = []

    for box, cls in zip(results[0].boxes.xyxy.cpu().numpy(),
                         results[0].boxes.cls.cpu().numpy()):

        x1, y1, x2, y2 = map(int, box)
        crop = img[y1:y2, x1:x2]

        if int(cls) == 0:
            dial_crop = crop
        else:
            pointer_crops.append({"class": int(cls), "crop": crop})

    # -------------------------
    # STEP 2: ODOMETER READING
    # -------------------------
    reading = 0

    if dial_crop is not None:
        temp_path = "/content/temp.jpg"
        cv2.imwrite(temp_path, dial_crop)

        results = odometer_yolo(temp_path)
        boxes = results[0].boxes.xyxy.cpu().numpy()
        boxes = sorted(boxes, key=lambda b: b[0])

        digits = []

        for b in boxes:
            x1, y1, x2, y2 = map(int, b)
            crop = dial_crop[y1:y2, x1:x2]
            crop = cv2.resize(crop, (64, 64))
            crop = crop.astype("float32") / 255.0
            digits.append(crop)

        if digits:
            preds = odometer_cnn.predict(np.array(digits), verbose=0)
            digits = np.argmax(preds, axis=1)
            reading = int("".join(map(str, digits)))

    # -------------------------
    # STEP 3: POINTER READING
    # -------------------------
    pointer_readings = []

    scales = {2: 0.01, 3: 0.001, 4: 0.0001}

    for p in pointer_crops:
        crop = cv2.resize(p["crop"], (64, 64))
        crop = crop.astype("float32") / 255.0

        pred = pointer_cnn.predict(np.expand_dims(crop, axis=0), verbose=0)
        value = np.argmax(pred, axis=1)[0]

        pointer_readings.append({
            "class": p["class"],
            "value": value
        })

    decimal_sum = 0
    for p in pointer_readings:
        decimal_sum += p["value"] * scales.get(p["class"], 0)

    final_value = reading + decimal_sum

    return final_value


# =========================
# BATCH PROCESSING
# =========================
results_list = []

for i, img_name in enumerate(images):
    path = os.path.join(image_folder, img_name)

    try:
        value = process_image(path)

        results_list.append({
            "id": i + 1,
            "image_name": img_name,
            "image_path": path,
            "predicted_reading": round(value, 4)
        })

        print(f"[{i+1}/{len(images)}] Done: {value}")

    except Exception as e:
        print(f"Error on {img_name}: {e}")

# =========================
# SAVE CSV
# =========================
df = pd.DataFrame(results_list)
csv_path = os.path.join(image_folder, "predicted_results.csv")
df.to_csv(csv_path, index=False)

