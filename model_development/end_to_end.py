general_model = YOLO("/content/drive/MyDrive/project/new water meter models/General best.pt")
odometer_yolo = YOLO("/content/drive/MyDrive/project/new water meter models/Odometer YOLO best.pt")
odometer_cnn  = load_model("/content/drive/MyDrive/project/new water meter models/digit_cnn_model.keras")
